/** What kind of thing an item is (item spec R3). A fixed list for now. */
export const ITEM_CATEGORIES = ['BOOK', 'COPY', 'PEN', 'PENCIL', 'BAG', 'TIE', 'OTHER'] as const;
export type ItemCategory = (typeof ITEM_CATEGORIES)[number];

/** The categories whose stock is counted by default (item spec R4, BRD FR-ITM-03); the API decides it again. */
export const STOCK_MANAGED_CATEGORIES: readonly ItemCategory[] = ['BOOK', 'COPY'];

/** The GST rates an item may carry, in percent (item spec R7). */
export const GST_RATES = [0, 5, 12, 18, 28] as const;

export const ITEM_STATUSES = ['ACTIVE', 'INACTIVE'] as const;
export type ItemStatus = (typeof ITEM_STATUSES)[number];

/** One row of `GET items`; the vendor's name comes from the vendor directory on the server. */
export interface ItemSummary {
  id: string;
  code: string;
  name: string;
  category: ItemCategory;
  className: string | null;
  vendorId: string | null;
  vendorName: string | null;
  gstRatePercent: number;
  isStockManaged: boolean;
  status: ItemStatus;
  createdAt: string;
}

/** `GET items/{id}`: the master data, the vendor, the barcodes and the status. */
export interface ItemDetail {
  id: string;
  code: string;
  name: string;
  category: ItemCategory;
  vendorId: string | null;
  vendorName: string | null;
  className: string | null;
  subject: string | null;
  hsnCode: string | null;
  gstRatePercent: number;
  isStockManaged: boolean;
  status: ItemStatus;
  createdAt: string;
  updatedAt: string | null;
  barcodes: string[];
}

export interface ItemSearchParams {
  search?: string;
  category?: ItemCategory;
  vendorId?: string;
  className?: string;
  isStockManaged?: boolean;
  status?: ItemStatus;
  orderBy?: string;
  pageIndex: number;
  pageSize: number;
}

/** The master data an Owner writes; the code is generated by the server and never sent (item spec R10). */
export interface ItemFields {
  name: string;
  category: ItemCategory;
  gstRatePercent: number;
  isStockManaged: boolean;
  vendorId?: string;
  className?: string;
  subject?: string;
  hsnCode?: string;
}
