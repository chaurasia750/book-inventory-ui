/** One row of `GET vendors`; the account number is masked (vendor spec R5). */
export interface VendorSummary {
  id: string;
  code: string;
  name: string;
  contactPerson: string | null;
  mobile: string | null;
  state: string | null;
  bankAccountMasked: string | null;
  status: VendorStatus;
  createdAt: string;
}

/** The five bank values; all given or none (vendor spec R5). */
export interface VendorBank {
  accountHolder: string;
  bankName: string;
  branch: string;
  accountNumber: string;
  ifsc: string;
}

/** `GET vendors/{id}`: the master data, the bank details in full (the Owner's view) and the status. */
export interface VendorDetail {
  id: string;
  code: string;
  name: string;
  address: string | null;
  contactPerson: string | null;
  mobile: string | null;
  email: string | null;
  gstin: string | null;
  state: string | null;
  bank: VendorBank | null;
  openingBalanceAmount: number;
  status: VendorStatus;
  createdAt: string;
  updatedAt: string | null;
}

export interface VendorSearchParams {
  search?: string;
  status?: VendorStatus;
  state?: string;
  orderBy?: string;
  pageIndex: number;
  pageSize: number;
}

/** The master data an Owner writes; the code is generated by the server and never sent (vendor spec R11). */
export interface VendorFields {
  name: string;
  openingBalanceAmount: number;
  state?: string;
  address?: string;
  contactPerson?: string;
  mobile?: string;
  email?: string;
  gstin?: string;
  bank?: VendorBank;
}
