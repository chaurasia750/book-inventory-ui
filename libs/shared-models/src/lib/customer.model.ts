export const CUSTOMER_STATUSES = ['ACTIVE', 'INACTIVE'] as const;
export type CustomerStatus = (typeof CUSTOMER_STATUSES)[number];

/** One row of `GET customers`; the school's name is read by the API through the school directory (customer spec R11). */
export interface CustomerSummary {
  id: string;
  code: string;
  name: string;
  mobile: string;
  schoolId: string | null;
  schoolName: string | null;
  className: string | null;
  status: CustomerStatus;
  createdAt: string;
}

/** One answer of `GET customers/suggest`: what a bill screen needs to choose a customer (customer spec R8). */
export interface CustomerSuggestion {
  id: string;
  code: string;
  name: string;
  mobile: string;
  schoolName: string | null;
}

/** `GET customers/{id}`: the master data, the opening balance, the credit limit and the status. */
export interface CustomerDetail {
  id: string;
  code: string;
  name: string;
  mobile: string;
  address: string | null;
  schoolId: string | null;
  schoolName: string | null;
  className: string | null;
  openingBalanceAmount: number;
  creditLimitAmount: number | null;
  status: CustomerStatus;
  createdAt: string;
  updatedAt: string | null;
}

export interface CustomerSearchParams {
  search?: string;
  status?: CustomerStatus;
  schoolId?: string;
  orderBy?: string;
  pageIndex: number;
  pageSize: number;
}

/** The master data written by the Owner or Staff; the code is generated by the server and never sent (customer spec R10). */
export interface CustomerFields {
  name: string;
  mobile: string;
  openingBalanceAmount: number;
  address?: string;
  schoolId?: string;
  className?: string;
  creditLimitAmount?: number;
}
