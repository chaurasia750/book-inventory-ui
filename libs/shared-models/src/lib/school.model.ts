/** How the school's year runs (school spec R3). */
export const SESSION_TYPES = ['APR_MAR', 'JAN_DEC'] as const;
export type SessionType = (typeof SESSION_TYPES)[number];

/** What the company sells to the school (school spec R4). */
export const SALE_TYPES = ['SCHOOL_ORDER', 'COUNTER_SALE', 'BOTH'] as const;
export type SaleType = (typeof SALE_TYPES)[number];

/** How a school pays (school spec R20): the default of its orders (sales R34). */
export const PAYMENT_TYPES = ['CASH', 'CREDIT'] as const;
export type PaymentType = (typeof PAYMENT_TYPES)[number];

export const SCHOOL_STATUSES = ['ACTIVE', 'INACTIVE'] as const;
export type SchoolStatus = (typeof SCHOOL_STATUSES)[number];

/** The states a school can be in. The business runs only in Bihar for now (school spec D6); the API checks it again. */
export const SCHOOL_STATES: readonly string[] = ['Bihar'];

/** One row of `GET schools`. */
export interface SchoolSummary {
  id: string;
  code: string;
  name: string;
  contactPerson: string | null;
  mobile: string | null;
  state: string;
  sessionType: SessionType;
  saleType: SaleType;
  status: SchoolStatus;
  createdAt: string;
}

export interface SchoolClassItem {
  id: string;
  name: string;
  sortOrder: number;
}

/** `GET schools/{id}`: the master data, the status and the class list. */
export interface SchoolDetail {
  id: string;
  code: string;
  name: string;
  address: string | null;
  contactPerson: string | null;
  mobile: string | null;
  email: string | null;
  gstin: string | null;
  state: string;
  sessionType: SessionType;
  saleType: SaleType;
  paymentType: PaymentType;
  isGstDefault: boolean;
  openingBalanceAmount: number;
  status: SchoolStatus;
  createdAt: string;
  updatedAt: string | null;
  classes: SchoolClassItem[];
}

export interface SchoolSearchParams {
  search?: string;
  status?: SchoolStatus;
  saleType?: SaleType;
  sessionType?: SessionType;
  state?: string;
  orderBy?: string;
  pageIndex: number;
  pageSize: number;
}

/** The master data an Owner writes; the code is generated by the server and never sent (school spec R15). */
export interface SchoolFields {
  name: string;
  sessionType: SessionType;
  saleType: SaleType;
  paymentType: PaymentType;
  isGstDefault: boolean;
  openingBalanceAmount: number;
  state?: string;
  address?: string;
  contactPerson?: string;
  mobile?: string;
  email?: string;
  gstin?: string;
}
