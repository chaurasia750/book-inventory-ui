import { ChangeDetectionStrategy, Component, effect, input, output } from '@angular/core';
import { FormControl, FormGroup, ReactiveFormsModule, Validators } from '@angular/forms';
import { TranslatePipe } from '@ngx-translate/core';
import { PAYMENT_TYPES, PaymentType, SALE_TYPES, SCHOOL_STATES, SESSION_TYPES, SaleType, SchoolDetail, SchoolFields, SessionType } from '@org/shared-models';
import { ButtonComponent } from '@org/ui';
import { MoneyPrefixComponent } from '../counters/money-prefix';

const FIELD = 'h-10 w-full rounded-xl border border-gray-200 bg-gray-50 px-3 text-sm focus:border-brand-400 focus:bg-white focus:outline-none focus:ring-2 focus:ring-brand-100';

/**
 * The school master data form (school spec R2-R5, R7) shared by the add dialog and the edit dialog. It holds no code field:
 * the code is generated by the server (R15) and is only shown, read-only, on the detail page. It validates what the API
 * validates (name length, balance not negative with two decimals) so the common mistakes show before the request; the
 * API answers anything else with a catalogue message that the caller shows.
 */
@Component({
  selector: 'app-school-form',
  standalone: true,
  imports: [ReactiveFormsModule, TranslatePipe, ButtonComponent, MoneyPrefixComponent],
  changeDetection: ChangeDetectionStrategy.OnPush,
  template: `
    <form [formGroup]="form" (ngSubmit)="submit()" class="space-y-4">
      @if (error()) {
        <p class="rounded-xl border border-red-200 bg-red-50 p-3 text-xs text-red-600" role="alert">{{ error() }}</p>
      }
      <div class="grid gap-4 sm:grid-cols-2">
        <div class="sm:col-span-2">
          <label for="sf-name" class="mb-1 block text-sm font-semibold">{{ 'school.fields.name' | translate }}<span class="text-red-500" aria-hidden="true"> *</span></label>
          <input id="sf-name" formControlName="name" class="${FIELD}" />
        </div>
        <div>
          <label for="sf-session" class="mb-1 block text-sm font-semibold">{{ 'school.fields.sessionType' | translate }}<span class="text-red-500" aria-hidden="true"> *</span></label>
          <select id="sf-session" formControlName="sessionType" class="${FIELD}">
            @for (t of sessionTypes; track t) { <option [value]="t">{{ 'school.sessionType.' + t | translate }}</option> }
          </select>
        </div>
        <div>
          <label for="sf-sale" class="mb-1 block text-sm font-semibold">{{ 'school.fields.saleType' | translate }}<span class="text-red-500" aria-hidden="true"> *</span></label>
          <select id="sf-sale" formControlName="saleType" class="${FIELD}">
            @for (t of saleTypes; track t) { <option [value]="t">{{ 'school.saleType.' + t | translate }}</option> }
          </select>
        </div>
        <div>
          <label for="sf-payment" class="mb-1 block text-sm font-semibold">{{ 'school.fields.paymentType' | translate }}<span class="text-red-500" aria-hidden="true"> *</span></label>
          <select id="sf-payment" formControlName="paymentType" class="${FIELD}">
            @for (t of paymentTypes; track t) { <option [value]="t">{{ 'school.paymentType.' + t | translate }}</option> }
          </select>
        </div>
        <div>
          <label for="sf-state" class="mb-1 block text-sm font-semibold">{{ 'school.fields.state' | translate }}</label>
          <select id="sf-state" formControlName="state" class="${FIELD}">
            @for (s of states; track s) { <option [value]="s">{{ s }}</option> }
          </select>
        </div>
        <div>
          <label for="sf-balance" class="mb-1 block text-sm font-semibold">{{ 'school.fields.openingBalance' | translate }}<span class="text-red-500" aria-hidden="true"> *</span></label>
          <app-money-prefix><input id="sf-balance" type="number" step="0.01" min="0" formControlName="openingBalanceAmount" class="${FIELD}" /></app-money-prefix>
        </div>
        <div>
          <label for="sf-contact" class="mb-1 block text-sm font-semibold">{{ 'school.fields.contactPerson' | translate }}</label>
          <input id="sf-contact" formControlName="contactPerson" class="${FIELD}" />
        </div>
        <div>
          <label for="sf-mobile" class="mb-1 block text-sm font-semibold">{{ 'school.fields.mobile' | translate }}</label>
          <input id="sf-mobile" formControlName="mobile" class="${FIELD}" />
        </div>
        <div>
          <label for="sf-email" class="mb-1 block text-sm font-semibold">{{ 'school.fields.email' | translate }}</label>
          <input id="sf-email" type="email" formControlName="email" class="${FIELD}" />
        </div>
        <div>
          <label for="sf-gstin" class="mb-1 block text-sm font-semibold">{{ 'school.fields.gstin' | translate }}</label>
          <input id="sf-gstin" formControlName="gstin" class="${FIELD}" />
        </div>
        <div class="sm:col-span-2">
          <label for="sf-address" class="mb-1 block text-sm font-semibold">{{ 'school.fields.address' | translate }}</label>
          <input id="sf-address" formControlName="address" class="${FIELD}" />
        </div>
        <label class="flex items-center gap-2 text-sm sm:col-span-2">
          <input type="checkbox" formControlName="isGstDefault" class="h-4 w-4 rounded border-gray-300" />
          {{ 'school.fields.gstDefault' | translate }}
        </label>
      </div>
      <div class="flex justify-end gap-2 border-t border-gray-100 pt-4">
        <app-button variant="secondary" (clicked)="cancelled.emit()">{{ 'users.cancel' | translate }}</app-button>
        <app-button type="submit" [loading]="saving()">{{ submitLabel() | translate }}</app-button>
      </div>
    </form>
  `,
})
export class SchoolFormComponent {
  /** The school being edited, or null for a new one. */
  school = input<SchoolDetail | null>(null);
  saving = input(false);
  error = input('');
  submitLabel = input('school.add.submit');

  submitted = output<SchoolFields>();
  cancelled = output<void>();

  readonly sessionTypes = SESSION_TYPES;
  readonly saleTypes = SALE_TYPES;
  readonly paymentTypes = PAYMENT_TYPES;
  readonly states = SCHOOL_STATES;

  readonly form = new FormGroup({
    name: new FormControl('', { nonNullable: true, validators: [Validators.required, Validators.minLength(2), Validators.maxLength(150)] }),
    sessionType: new FormControl<SessionType>('APR_MAR', { nonNullable: true }),
    saleType: new FormControl<SaleType>('BOTH', { nonNullable: true }),
    paymentType: new FormControl<PaymentType>('CREDIT', { nonNullable: true }),
    state: new FormControl(SCHOOL_STATES[0], { nonNullable: true }),
    openingBalanceAmount: new FormControl(0, { nonNullable: true, validators: [Validators.required, Validators.min(0)] }),
    isGstDefault: new FormControl(false, { nonNullable: true }),
    contactPerson: new FormControl('', { nonNullable: true }),
    mobile: new FormControl('', { nonNullable: true }),
    email: new FormControl('', { nonNullable: true }),
    gstin: new FormControl('', { nonNullable: true }),
    address: new FormControl('', { nonNullable: true }),
  });

  constructor() {
    effect(() => {
      const s = this.school();
      this.form.reset(
        s
          ? {
              name: s.name,
              sessionType: s.sessionType,
              saleType: s.saleType,
              paymentType: s.paymentType,
              state: s.state,
              openingBalanceAmount: s.openingBalanceAmount,
              isGstDefault: s.isGstDefault,
              contactPerson: s.contactPerson ?? '',
              mobile: s.mobile ?? '',
              email: s.email ?? '',
              gstin: s.gstin ?? '',
              address: s.address ?? '',
            }
          : { name: '', sessionType: 'APR_MAR', saleType: 'BOTH', paymentType: 'CREDIT', state: SCHOOL_STATES[0], openingBalanceAmount: 0, isGstDefault: false },
      );
    });
  }

  submit(): void {
    if (this.form.invalid || this.saving()) {
      this.form.markAllAsTouched();
      return;
    }

    const v = this.form.getRawValue();
    this.submitted.emit({
      name: v.name.trim(),
      sessionType: v.sessionType,
      saleType: v.saleType,
      paymentType: v.paymentType,
      state: v.state,
      openingBalanceAmount: Math.round(v.openingBalanceAmount * 100) / 100,
      isGstDefault: v.isGstDefault,
      contactPerson: v.contactPerson.trim(),
      mobile: v.mobile.trim(),
      email: v.email.trim(),
      gstin: v.gstin.trim(),
      address: v.address.trim(),
    });
  }
}
