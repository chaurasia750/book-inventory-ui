import { ChangeDetectionStrategy, Component, DestroyRef, effect, inject, input, output, signal } from '@angular/core';
import { takeUntilDestroyed } from '@angular/core/rxjs-interop';
import { FormControl, FormGroup, ReactiveFormsModule, Validators } from '@angular/forms';
import { TranslatePipe } from '@ngx-translate/core';
import { VendorService } from '@org/api-services';
import {
  GST_RATES,
  ITEM_CATEGORIES,
  ItemCategory,
  ItemDetail,
  ItemFields,
  STOCK_MANAGED_CATEGORIES,
} from '@org/shared-models';
import { ButtonComponent } from '@org/ui';

const FIELD = 'h-10 w-full rounded-xl border border-gray-200 bg-gray-50 px-3 text-sm focus:border-brand-400 focus:bg-white focus:outline-none focus:ring-2 focus:ring-brand-100';

interface VendorOption {
  id: string;
  name: string;
}

/**
 * The item master data form (item spec R2-R5, R7) shared by the add and the edit panel. There is no code field: the code is
 * generated by the server (R10) and only shown on the detail; the barcodes are edited on the detail (R6). A new item takes the
 * stock-managed default of its category until the Owner touches the checkbox (R4). The vendor is chosen from the company's
 * active vendors (R5); an item whose vendor was deactivated later keeps it as an option.
 */
@Component({
  selector: 'app-item-form',
  standalone: true,
  imports: [ReactiveFormsModule, TranslatePipe, ButtonComponent],
  changeDetection: ChangeDetectionStrategy.OnPush,
  template: `
    <form [formGroup]="form" (ngSubmit)="submit()" class="space-y-5">
      @if (error()) {
        <p class="rounded-xl border border-red-200 bg-red-50 p-3 text-xs text-red-600" role="alert">{{ error() }}</p>
      }
      <div class="grid gap-4 sm:grid-cols-2">
        <div class="sm:col-span-2">
          <label for="if-name" class="mb-1 block text-sm font-semibold">{{ 'item.fields.name' | translate }}<span class="text-red-500" aria-hidden="true"> *</span></label>
          <input id="if-name" formControlName="name" class="${FIELD}" />
        </div>
        <div>
          <label for="if-category" class="mb-1 block text-sm font-semibold">{{ 'item.fields.category' | translate }}<span class="text-red-500" aria-hidden="true"> *</span></label>
          <select id="if-category" formControlName="category" class="${FIELD}">
            @for (c of categories; track c) { <option [value]="c">{{ 'item.category.' + c | translate }}</option> }
          </select>
        </div>
        <div>
          <label for="if-vendor" class="mb-1 block text-sm font-semibold">{{ 'item.fields.vendor' | translate }}</label>
          <select id="if-vendor" formControlName="vendorId" class="${FIELD}">
            <option value="">{{ 'item.fields.noVendor' | translate }}</option>
            @for (v of vendorOptions(); track v.id) { <option [value]="v.id">{{ v.name }}</option> }
          </select>
        </div>
        <div>
          <label for="if-class" class="mb-1 block text-sm font-semibold">{{ 'item.fields.className' | translate }}</label>
          <input id="if-class" formControlName="className" class="${FIELD}" />
        </div>
        <div>
          <label for="if-subject" class="mb-1 block text-sm font-semibold">{{ 'item.fields.subject' | translate }}</label>
          <input id="if-subject" formControlName="subject" class="${FIELD}" />
        </div>
        <div>
          <label for="if-hsn" class="mb-1 block text-sm font-semibold">{{ 'item.fields.hsnCode' | translate }}</label>
          <input id="if-hsn" inputmode="numeric" formControlName="hsnCode" class="${FIELD}" />
          <p class="mt-1 text-xs text-gray-500">{{ 'item.fields.hsnHint' | translate }}</p>
        </div>
        <div>
          <label for="if-gst" class="mb-1 block text-sm font-semibold">{{ 'item.fields.gstRate' | translate }}<span class="text-red-500" aria-hidden="true"> *</span></label>
          <select id="if-gst" formControlName="gstRatePercent" class="${FIELD}">
            @for (r of gstRates; track r) { <option [ngValue]="r">{{ r }}%</option> }
          </select>
        </div>
        <label class="flex items-center gap-2 text-sm sm:col-span-2">
          <input type="checkbox" formControlName="isStockManaged" class="h-4 w-4 rounded border-gray-300" />
          {{ 'item.fields.stockManaged' | translate }}
        </label>
      </div>
      <div class="flex justify-end gap-2 border-t border-gray-100 pt-4">
        <app-button variant="secondary" (clicked)="cancelled.emit()">{{ 'users.cancel' | translate }}</app-button>
        <app-button type="submit" [loading]="saving()">{{ submitLabel() | translate }}</app-button>
      </div>
    </form>
  `,
})
export class ItemFormComponent {
  /** The item being edited, or null for a new one. */
  item = input<ItemDetail | null>(null);
  saving = input(false);
  error = input('');
  submitLabel = input('item.add.submit');

  submitted = output<ItemFields>();
  cancelled = output<void>();

  private readonly vendors = inject(VendorService);
  private readonly destroyRef = inject(DestroyRef);

  readonly categories = ITEM_CATEGORIES;
  readonly gstRates = GST_RATES;
  readonly vendorOptions = signal<VendorOption[]>([]);

  readonly form = new FormGroup({
    name: new FormControl('', { nonNullable: true, validators: [Validators.required, Validators.minLength(2), Validators.maxLength(200)] }),
    category: new FormControl<ItemCategory>('BOOK', { nonNullable: true, validators: [Validators.required] }),
    vendorId: new FormControl('', { nonNullable: true }),
    className: new FormControl('', { nonNullable: true, validators: [Validators.maxLength(50)] }),
    subject: new FormControl('', { nonNullable: true, validators: [Validators.maxLength(100)] }),
    hsnCode: new FormControl('', { nonNullable: true, validators: [Validators.pattern(/^(\d{4,8})?$/)] }),
    gstRatePercent: new FormControl<number>(0, { nonNullable: true, validators: [Validators.required] }),
    isStockManaged: new FormControl(true, { nonNullable: true }),
  });

  constructor() {
    this.form.controls.category.valueChanges.pipe(takeUntilDestroyed(this.destroyRef)).subscribe((category) => {
      if (!this.form.controls.isStockManaged.dirty) {
        this.form.controls.isStockManaged.setValue(STOCK_MANAGED_CATEGORIES.includes(category));
      }
    });

    this.vendors
      .list({ status: 'ACTIVE', orderBy: 'Name ASC', pageIndex: 1, pageSize: 200 })
      .pipe(takeUntilDestroyed(this.destroyRef))
      .subscribe((result) => this.vendorOptions.set(this.withCurrentVendor(result.items.map((v) => ({ id: v.id, name: v.name })))));

    effect(() => {
      const item = this.item();
      this.form.reset(
        item
          ? {
              name: item.name,
              category: item.category,
              vendorId: item.vendorId ?? '',
              className: item.className ?? '',
              subject: item.subject ?? '',
              hsnCode: item.hsnCode ?? '',
              gstRatePercent: item.gstRatePercent,
              isStockManaged: item.isStockManaged,
            }
          : { name: '', category: 'BOOK', vendorId: '', gstRatePercent: 0, isStockManaged: true },
      );
      this.vendorOptions.update((options) => this.withCurrentVendor(options));
    });
  }

  submit(): void {
    if (this.form.invalid || this.saving()) {
      this.form.markAllAsTouched();
      return;
    }

    const v = this.form.getRawValue();
    this.submitted.emit({
      name: v.name.trim(),
      category: v.category,
      gstRatePercent: v.gstRatePercent,
      isStockManaged: v.isStockManaged,
      vendorId: v.vendorId || undefined,
      className: v.className.trim(),
      subject: v.subject.trim(),
      hsnCode: v.hsnCode.trim(),
    });
  }

  /** An item whose vendor was deactivated later keeps it (item spec R5): it is offered next to the active vendors. */
  private withCurrentVendor(options: VendorOption[]): VendorOption[] {
    const item = this.item();
    if (item?.vendorId && item.vendorName && !options.some((o) => o.id === item.vendorId)) {
      return [{ id: item.vendorId, name: item.vendorName }, ...options];
    }
    return options;
  }
}
