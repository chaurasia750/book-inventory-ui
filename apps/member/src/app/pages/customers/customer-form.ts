import { ChangeDetectionStrategy, Component, DestroyRef, effect, inject, input, output, signal, untracked } from '@angular/core';
import { takeUntilDestroyed } from '@angular/core/rxjs-interop';
import { FormControl, FormGroup, ReactiveFormsModule, Validators } from '@angular/forms';
import { TranslatePipe } from '@ngx-translate/core';
import { SchoolService } from '@org/api-services';
import { CustomerDetail, CustomerFields } from '@org/shared-models';
import { ButtonComponent, SchoolSelectComponent } from '@org/ui';
import { MoneyPrefixComponent } from '../counters/money-prefix';

const FIELD = 'h-10 w-full rounded-xl border border-gray-200 bg-gray-50 px-3 text-sm focus:border-brand-400 focus:bg-white focus:outline-none focus:ring-2 focus:ring-brand-100';

/**
 * The customer master data form (customer spec R2-R7) shared by the add and the edit panel. There is no code field: the code is
 * generated by the server (R10) and only shown on the detail. It validates what the API validates (name length, mobile present,
 * amounts) so the common mistakes show before the request. The class select appears once a school is chosen and lists that
 * school's classes (R4); the API checks everything again and its catalogue message is shown on a refusal.
 */
@Component({
  selector: 'app-customer-form',
  standalone: true,
  imports: [ReactiveFormsModule, TranslatePipe, ButtonComponent, SchoolSelectComponent, MoneyPrefixComponent],
  changeDetection: ChangeDetectionStrategy.OnPush,
  template: `
    <form [formGroup]="form" (ngSubmit)="submit()" class="space-y-5">
      @if (error()) {
        <p class="rounded-xl border border-red-200 bg-red-50 p-3 text-xs text-red-600" role="alert">{{ error() }}</p>
      }
      <div class="grid gap-4 sm:grid-cols-2">
        <div class="sm:col-span-2">
          <label for="cf-name" class="mb-1 block text-sm font-semibold">{{ 'customer.fields.name' | translate }}<span class="text-red-500" aria-hidden="true"> *</span></label>
          <input id="cf-name" formControlName="name" class="${FIELD}" />
        </div>
        <div>
          <label for="cf-mobile" class="mb-1 block text-sm font-semibold">{{ 'customer.fields.mobile' | translate }}<span class="text-red-500" aria-hidden="true"> *</span></label>
          <input id="cf-mobile" inputmode="tel" formControlName="mobile" class="${FIELD}" />
        </div>
        <div>
          <label for="cf-address" class="mb-1 block text-sm font-semibold">{{ 'customer.fields.address' | translate }}</label>
          <input id="cf-address" formControlName="address" class="${FIELD}" />
        </div>
        <div>
          <label for="cf-school" class="mb-1 block text-sm font-semibold">{{ 'customer.fields.school' | translate }}</label>
          <app-school-select inputId="cf-school" formControlName="schoolId" [placeholder]="'customer.fields.noSchool' | translate" [searchPlaceholder]="'counter.fields.searchSchool' | translate"
            [emptyLabel]="'counter.fields.noSchoolFound' | translate" [allLabel]="'customer.fields.noSchool' | translate" (picked)="schoolChanged()" />
        </div>
        <div>
          <label for="cf-class" class="mb-1 block text-sm font-semibold">{{ 'customer.fields.className' | translate }}</label>
          <select id="cf-class" formControlName="className" class="${FIELD}">
            <option value="">{{ 'customer.fields.noClass' | translate }}</option>
            @for (name of classes(); track name) { <option [value]="name">{{ name }}</option> }
          </select>
          @if (!form.controls.schoolId.value) {
            <p class="mt-1 text-xs text-gray-500">{{ 'customer.fields.classHint' | translate }}</p>
          }
        </div>
        <div>
          <label for="cf-balance" class="mb-1 block text-sm font-semibold">{{ 'customer.fields.openingBalance' | translate }}<span class="text-red-500" aria-hidden="true"> *</span></label>
          <app-money-prefix><input id="cf-balance" type="number" step="0.01" min="0" formControlName="openingBalanceAmount" class="${FIELD}" /></app-money-prefix>
          <p class="mt-1 text-xs text-gray-500">{{ 'customer.fields.openingBalanceHint' | translate }}</p>
        </div>
        <div>
          <label for="cf-limit" class="mb-1 block text-sm font-semibold">{{ 'customer.fields.creditLimit' | translate }}</label>
          <app-money-prefix><input id="cf-limit" type="number" step="0.01" min="0.01" formControlName="creditLimitAmount" class="${FIELD}" /></app-money-prefix>
          <p class="mt-1 text-xs text-gray-500">{{ 'customer.fields.creditLimitHint' | translate }}</p>
        </div>
      </div>

      <div class="flex justify-end gap-2 border-t border-gray-100 pt-4">
        <app-button variant="secondary" (clicked)="cancelled.emit()">{{ 'users.cancel' | translate }}</app-button>
        <app-button type="submit" [loading]="saving()">{{ submitLabel() | translate }}</app-button>
      </div>
    </form>
  `,
})
export class CustomerFormComponent {
  private readonly schoolService = inject(SchoolService);
  private readonly destroyRef = inject(DestroyRef);

  /** The customer being edited, or null for a new one. */
  customer = input<CustomerDetail | null>(null);
  saving = input(false);
  error = input('');
  submitLabel = input('customer.add.submit');

  submitted = output<CustomerFields>();
  cancelled = output<void>();

  readonly classes = signal<string[]>([]);

  readonly form = new FormGroup({
    name: new FormControl('', { nonNullable: true, validators: [Validators.required, Validators.minLength(2), Validators.maxLength(150)] }),
    mobile: new FormControl('', { nonNullable: true, validators: [Validators.required] }),
    address: new FormControl('', { nonNullable: true }),
    schoolId: new FormControl('', { nonNullable: true }),
    className: new FormControl('', { nonNullable: true }),
    openingBalanceAmount: new FormControl(0, { nonNullable: true, validators: [Validators.required, Validators.min(0)] }),
    creditLimitAmount: new FormControl<number | null>(null, { validators: [Validators.min(0.01)] }),
  });

  constructor() {
    effect(() => {
      const c = this.customer();
      untracked(() => this.fill(c));
    });
  }

  private fill(c: CustomerDetail | null): void {
    this.form.reset(
      c
        ? {
            name: c.name,
            mobile: c.mobile,
            address: c.address ?? '',
            schoolId: c.schoolId ?? '',
            className: c.className ?? '',
            openingBalanceAmount: c.openingBalanceAmount,
            creditLimitAmount: c.creditLimitAmount,
          }
        : { name: '', mobile: '', address: '', schoolId: '', className: '', openingBalanceAmount: 0, creditLimitAmount: null },
    );
    this.loadClasses(c?.className ?? '');
  }

  /** The class list follows the chosen school; a school change clears the old class (customer spec R4). */
  schoolChanged(): void {
    this.form.controls.className.setValue('');
    this.loadClasses('');
  }

  submit(): void {
    if (this.form.invalid || this.saving()) {
      this.form.markAllAsTouched();
      return;
    }

    const v = this.form.getRawValue();
    this.submitted.emit({
      name: v.name.trim(),
      mobile: v.mobile.trim(),
      openingBalanceAmount: Math.round(v.openingBalanceAmount * 100) / 100,
      address: v.address.trim(),
      schoolId: v.schoolId || undefined,
      className: v.schoolId ? v.className : undefined,
      creditLimitAmount: v.creditLimitAmount === null ? undefined : Math.round(v.creditLimitAmount * 100) / 100,
    });
  }

  private loadClasses(selected: string): void {
    const schoolId = this.form.controls.schoolId.value;
    if (!schoolId) {
      this.classes.set([]);
      return;
    }

    this.schoolService
      .get(schoolId)
      .pipe(takeUntilDestroyed(this.destroyRef))
      .subscribe({
        next: (school) => {
          this.classes.set(school.classes.map((c) => c.name));
          this.form.controls.className.setValue(selected);
        },
        error: () => this.classes.set([]),
      });
  }
}
